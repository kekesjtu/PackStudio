"""Build the automatic and merged material libraries from captured FloXML."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import xml.etree.ElementTree as ET
from collections import defaultdict
from datetime import datetime
from pathlib import Path
from typing import Any

PROPERTY_NAMES = {
    "density": "density_kg_m3",
    "specific_heat": "specific_heat_j_kg_k",
    "conductivity": "conductivity_w_m_k",
    "x_conductivity": "x_conductivity_w_m_k",
    "y_conductivity": "y_conductivity_w_m_k",
    "z_conductivity": "z_conductivity_w_m_k",
    "in_plane_conductivity": "in_plane_conductivity_w_m_k",
    "normal_conductivity": "normal_conductivity_w_m_k",
    "coeff": "conductivity_temperature_coefficient",
    "tref": "reference_temperature_k",
}

MODEL_NAMES = {
    "isotropic_material_att": "isotropic",
    "orthotropic_material_att": "orthotropic",
    "biaxial_material_att": "biaxial",
    "temperature_dependant_material_att": "temperature_dependent",
}


def parse_number(text: str) -> int | float | str:
    try:
        value = float(text)
    except ValueError:
        return text
    return int(value) if value.is_integer() else value


def slugify(value: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", value.lower()).strip("_")
    return slug or "material"


def definition_id(material: dict[str, Any]) -> str:
    payload = json.dumps(material, sort_keys=True, separators=(",", ":"))
    digest = hashlib.sha256(payload.encode("utf-8")).hexdigest()[:12]
    return f"floxml_{slugify(material['name'])}_{digest}"


def source_path(path: Path, data_root: Path) -> str:
    return path.resolve().relative_to(data_root.resolve()).as_posix()


def collect_materials(
    templates_root: Path, data_root: Path
) -> tuple[list[str], list[dict[str, Any]], int]:
    model_files = sorted(templates_root.glob("*/baseline/model.xml"))
    definitions: dict[str, dict[str, Any]] = {}
    source_sets: dict[str, set[str]] = defaultdict(set)
    occurrence_count = 0

    for model_file in model_files:
        materials = ET.parse(model_file).getroot().find("./attributes/materials")
        if materials is None:
            continue
        source = source_path(model_file, data_root)
        for element in materials:
            name_element = element.find("name")
            if name_element is None or not name_element.text:
                continue
            properties = {
                PROPERTY_NAMES.get(child.tag, child.tag): parse_number((child.text or "").strip())
                for child in element
                if child.tag != "name"
            }
            material = {
                "name": name_element.text.strip(),
                "model": MODEL_NAMES.get(element.tag, element.tag),
                "floxml_type": element.tag,
                **properties,
            }
            key = definition_id(material)
            definitions[key] = {"material_id": key, **material}
            source_sets[key].add(source)
            occurrence_count += 1

    records = []
    for key, material in definitions.items():
        record = {
            **material,
            "source_type": "floxml",
            "source_files": sorted(source_sets[key]),
        }
        if material["name"] == "Bumps":
            record["notes"] = (
                "Equivalent bump-layer material generated by FloTHERM PACK; "
                "consult the manually captured constituent solder and "
                "underfill records."
            )
        elif material["name"] == "Solder_ball":
            record["notes"] = (
                "Equivalent material generated for an orthotropic solder-ball-array representation."
            )
        records.append(record)

    records.sort(key=lambda item: (item["name"].casefold(), item["material_id"]))
    return (
        [source_path(path, data_root) for path in model_files],
        records,
        occurrence_count,
    )


def collision_report(materials: list[dict[str, Any]]) -> list[dict[str, Any]]:
    by_name: dict[str, list[str]] = defaultdict(list)
    for material in materials:
        by_name[material["name"]].append(material["material_id"])
    return [
        {
            "name": name,
            "definition_count": len(material_ids),
            "material_ids": material_ids,
        }
        for name, material_ids in sorted(by_name.items())
        if len(material_ids) > 1
    ]


def manual_records(manual_library: dict[str, Any]) -> list[dict[str, Any]]:
    records = []
    for material in manual_library["materials"]:
        name = material["name"]
        record = {
            "material_id": f"manual_{slugify(name)}",
            **material,
            "source_type": "manual_ui_capture",
        }
        records.append(record)
    return records


def write_libraries(data_root: Path, generated_at: str) -> None:
    materials_dir = data_root / "materials"
    source_files, materials, occurrence_count = collect_materials(
        data_root / "templates", data_root
    )
    collisions = collision_report(materials)
    automatic = {
        "schema_version": "1.0",
        "generated_at": generated_at,
        "status": "complete",
        "scope": {
            "included": ["templates/*/baseline/model.xml"],
            "excluded": [
                "templates/*/xml_variations/*/*/model.xml",
                "templates/*/validation/*.xml",
            ],
            "exclusion_reason": (
                "The agreed material policy is default-only; sweep and replay "
                "models are excluded to prevent derived variants from entering "
                "the default library."
            ),
        },
        "statistics": {
            "source_file_count": len(source_files),
            "material_occurrence_count": occurrence_count,
            "unique_definition_count": len(materials),
            "distinct_name_count": len({item["name"] for item in materials}),
            "colliding_name_count": len(collisions),
        },
        "source_files": source_files,
        "name_collisions": collisions,
        "materials": materials,
    }
    (materials_dir / "materials_auto_extracted.json").write_text(
        json.dumps(automatic, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    manual_path = materials_dir / "materials_manual_captured.json"
    manual = json.loads(manual_path.read_text(encoding="utf-8"))
    merged_materials = [
        *materials,
        *manual_records(manual),
    ]
    merged_materials.sort(key=lambda item: (item["name"].casefold(), item["material_id"]))
    master = {
        "schema_version": "1.0",
        "generated_at": generated_at,
        "status": "complete",
        "merge_policy": {
            "floxml_identity": ("name + model + exact exported thermophysical properties"),
            "name_collisions": ("Preserve every distinct definition and its source files."),
            "manual_capture": (
                "Add hidden constituent materials without replacing generated "
                "equivalent-layer definitions."
            ),
        },
        "statistics": {
            "automatic_definition_count": len(materials),
            "manual_definition_count": len(manual["materials"]),
            "total_definition_count": len(merged_materials),
        },
        "sources": {
            "automatic": "materials/materials_auto_extracted.json",
            "manual": "materials/materials_manual_captured.json",
        },
        "materials": merged_materials,
    }
    (materials_dir / "master_material_library.json").write_text(
        json.dumps(master, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "data_root",
        nargs="?",
        type=Path,
        default=Path("flotherm_pack_data"),
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    generated_at = datetime.now().astimezone().isoformat(timespec="seconds")
    write_libraries(args.data_root, generated_at)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
